"""Camada de compatibilidade PostgreSQL para a API SQLite legada do EstudaTI.

Uso: DATABASE_URL=postgresql://... habilita PostgreSQL; sem DATABASE_URL,
o sistema permanece no SQLite atual. Nunca registrar credenciais em logs.
Testar em banco isolado antes de apontar à produção.
"""
import re
from collections.abc import Iterator

# Estas tabelas usam id INTEGER PRIMARY KEY como identificador gerado pelo SQLite.
_AUTO_ID = frozenset({
    "topics", "flashcards", "questions", "quiz_attempts", "quiz_answers",
    "sessions", "plan_items", "contests", "recall_checks",
    "discursive_questions", "discursive_attempts", "question_audit",
    "syllabus_items",
})
_TABLE_INFO = re.compile(r"^\s*PRAGMA\s+table_info\((\w+)\)\s*$", re.I)
_INSERT = re.compile(r"^\s*INSERT\s+(?:OR\s+IGNORE\s+)?INTO\s+(\w+)\b", re.I)
_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", re.I)
_ID_COL = re.compile(r"\bid\s+INTEGER\s+PRIMARY\s+KEY\b(?!\s+REFERENCES)", re.I)
_QMARK = re.compile(r"\?")


class PgRow(dict):
    """Combina row['coluna'], row[0] e dict(row) usados na API SQLite."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def _rows(rows):
    return [PgRow(r) for r in rows]


def _adapt_sql(statement):
    sql = statement.strip().rstrip(";")
    if not sql:
        return ""
    sql = _ID_COL.sub("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    sql = _OR_IGNORE.sub("INSERT INTO", sql)
    ignoring = bool(_OR_IGNORE.match(statement.strip()))
    if ignoring:
        sql += " ON CONFLICT DO NOTHING"
    sql = re.sub(r"datetime\(\s*'now'\s*\)",
                 "to_char(NOW() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')",
                 sql, flags=re.I)
    sql = re.sub(r"date\(\s*'now'\s*\)",
                 "to_char(CURRENT_DATE,'YYYY-MM-DD')",
                 sql, flags=re.I)
    # As instruções do projeto utilizam ? apenas como marcadores de parâmetros;
    # valores do usuário passam obrigatoriamente como parâmetros separados.
    return _QMARK.sub("%s", sql)


class PgCursor:
    def __init__(self, cursor=None, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    @property
    def rowcount(self):
        return self._cursor.rowcount if self._cursor else 0

    def fetchone(self):
        if not self._cursor:
            return None
        row = self._cursor.fetchone()
        return PgRow(row) if row is not None else None

    def fetchall(self):
        if not self._cursor:
            return []
        return _rows(self._cursor.fetchall())

    def __iter__(self) -> Iterator[PgRow]:
        if self._cursor:
            for row in self._cursor:
                yield PgRow(row)


class PgConnection:
    """Adaptador de conexão transacional com a pequena API usada pelo projeto."""
    def __init__(self, database_url):
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError("Instale psycopg[binary] para usar DATABASE_URL") from exc
        self._db = psycopg.connect(database_url, row_factory=dict_row,
                                   connect_timeout=20)

    def __enter__(self):
        return self

    def __exit__(self, error_type, error, traceback):
        try:
            if error_type is None:
                self._db.commit()
            else:
                self._db.rollback()
        finally:
            self._db.close()
        return False

    def execute(self, sql, params=()):
        pragma = _TABLE_INFO.match(sql)
        if pragma:
            sql = """SELECT column_name AS name
                      FROM information_schema.columns
                      WHERE table_schema = current_schema() AND table_name = %s
                      ORDER BY ordinal_position"""
            params = (pragma.group(1),)
        elif sql.lstrip().upper().startswith("PRAGMA "):
            return PgCursor()
        else:
            sql = _adapt_sql(sql)
        if not sql:
            return PgCursor()
        matched = _INSERT.match(sql)
        has_auto_id = bool(matched and matched.group(1).lower() in _AUTO_ID)
        if has_auto_id and not re.search(r"\bRETURNING\b", sql, re.I):
            sql += " RETURNING id"
        cur = self._db.cursor()
        cur.execute(sql, params or ())
        last = None
        if has_auto_id:
            item = cur.fetchone()
            if item:
                last = item["id"]
        return PgCursor(cur, lastrowid=last)

    def executescript(self, statements):
        # As únicas scripts do projeto contêm definições de tabelas/índices
        # (sem ponto-e-vírgula dentro de strings).
        for sql in statements.split(";"):
            if sql.strip():
                self.execute(sql)

    def executemany(self, sql, many):
        result = PgCursor()
        for params in many:
            result = self.execute(sql, params)
        return result


def connect(database_url):
    if not database_url:
        raise ValueError("DATABASE_URL não informada")
    return PgConnection(database_url)
